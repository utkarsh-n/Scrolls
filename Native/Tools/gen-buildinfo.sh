#!/bin/zsh
# OWNER: N0
# Writes ScrollsKit/Sources/ScrollsCore/Generated/BuildInfo.swift INSIDE A BUILD MIRROR (never the iCloud tree).
#   Tools/gen-buildinfo.sh <mirrored Scrolls dir> [dev|full]
# dev  — the committed "dev" values: stable bytes, so quick builds and tests stay incremental (default for target/test).
# full — engineVersion, gitCommit, sourceDigest and per-stage code hashes (default for cli, sim, app-test, device).
# Per-stage hashes cover the targets that implement the stage (IOS-SPEC §1.2): coarse on purpose, so a code change can
# only cause an unneeded recount, never a missed one. The file is replaced only when its content changes.
set -euo pipefail
SRC="${1:?usage: gen-buildinfo.sh <mirrored Scrolls dir> [dev|full]}"
MODE="${2:-${SCROLLS_BUILDINFO:-dev}}"
case "$SRC" in "$HOME/Documents"*|*"/Mobile Documents/"*) echo "gen-buildinfo.sh: refusing to write into iCloud ($SRC)" >&2; exit 2 ;; esac
KIT="$SRC/Native/ScrollsKit/Sources"
OUT="$KIT/ScrollsCore/Generated/BuildInfo.swift"
mkdir -p "${OUT:h}"
TMP="$(mktemp "${TMPDIR:-/tmp}/buildinfo.XXXXXX")"
trap 'rm -f "$TMP"' EXIT

digest() {  # sha256 over "path sha" lines of every .swift/.metal/.h/.sql/.json source under the given targets
  local list=()
  for t in "$@"; do [[ -d "$KIT/$t" ]] && list+=("$KIT/$t"); done
  (( ${#list} )) || { echo "none"; return; }
  find "${list[@]}" -type f \( -name '*.swift' -o -name '*.metal' -o -name '*.h' -o -name '*.sql' -o -name '*.json' \) \
       ! -path '*/Generated/BuildInfo.swift' -print0 | LC_ALL=C sort -z | xargs -0 shasum -a 256 \
    | sed "s|$KIT/||" | shasum -a 256 | cut -d' ' -f1
}

if [[ "$MODE" == dev ]]; then
  ENGINE=dev; COMMIT=dev; DIGEST=dev; STAGES=""
else
  ENGINE="$(awk -F'"' '/MARKETING_VERSION:/ {print $2; exit}' "$SRC/Native/project.yml" 2>/dev/null)"
  COMMIT="$(git --git-dir="${SCROLLS_GIT_DIR:-$HOME/Developer/git/Scrolls.git}" rev-parse HEAD 2>/dev/null || echo unknown)"
  DIGEST="$(digest ScrollsCore ScrollsContracts ScrollsStore ScrollsJobs ScrollsIngest ScrollsSources ScrollsQuery \
            ScrollsAnalysis ScrollsNL ScrollsLineage ScrollsProvenance ScrollsService ScrollsScrollModel ScrollsRender)"
  INGEST="$(digest ScrollsCore ScrollsStore ScrollsIngest ScrollsSources)"
  QUERY="$(digest ScrollsCore ScrollsStore ScrollsQuery)"
  ANALYSIS="$(digest ScrollsCore ScrollsStore ScrollsQuery ScrollsAnalysis)"
  NL="$(digest ScrollsCore ScrollsStore ScrollsQuery ScrollsAnalysis ScrollsNL)"
  LINEAGE="$(digest ScrollsCore ScrollsStore ScrollsQuery ScrollsAnalysis ScrollsLineage)"
  STAGES=""
  for s in import demo-load bootstrap-cipher adapter-load cipher_load; do STAGES+="    \"$s\": \"$INGEST\",\n"; done
  for s in materialize export; do STAGES+="    \"$s\": \"$QUERY\",\n"; done
  for s in tokstream collocations vectors align cluster drift layout; do STAGES+="    \"$s\": \"$ANALYSIS\",\n"; done
  STAGES+="    \"tone\": \"$NL\",\n"
  for s in boilerplate reuse-index trace; do STAGES+="    \"$s\": \"$LINEAGE\",\n"; done
fi

{
  print -r -- '// OWNER: N0'
  print -r -- "// GENERATED by Native/Tools/gen-buildinfo.sh ($MODE) in a build mirror. The committed copy holds \"dev\" values."
  print -r -- ''
  print -r -- '/// The identity of this engine build: runs record `codeHash(stage:)` as their `code_hash` (ΔS-7).'
  print -r -- 'public enum BuildInfo {'
  print -r -- '  /// MARKETING_VERSION of Native/project.yml.'
  print -r -- "  public static let engineVersion = \"$ENGINE\""
  print -r -- '  /// HEAD of ~/Developer/git/Scrolls.git when the mirror was made.'
  print -r -- "  public static let gitCommit = \"$COMMIT\""
  print -r -- '  /// sha256 over every engine source file (path and content).'
  print -r -- "  public static let sourceDigest = \"$DIGEST\""
  print -r -- "  /// sha256 of each stage's source files, the analogue of the reference's MATCHING_CODE_FILES."
  if [[ -z "$STAGES" ]]; then
    print -r -- '  public static let stageCodeHashes: [String: String] = [:]'
  else
    print -r -- '  public static let stageCodeHashes: [String: String] = ['
    print -n -- "$STAGES"
    print -r -- '  ]'
  fi
  print -r -- ''
  print -r -- '  /// The code hash a run of `stage` records: its own hash, or the source digest for a stage without one.'
  print -r -- '  public static func codeHash(stage: String) -> String { stageCodeHashes[stage] ?? sourceDigest }'
  print -r -- '}'
} > "$TMP"

if ! cmp -s "$TMP" "$OUT" 2>/dev/null; then cp "$TMP" "$OUT"; fi
