export function generate(ctx) {
  const dir = join(ctx.refRoot, 'server/text/stopwords');
  const langs = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
  let out = '// OWNER: N4 — generated by Native/Golden/gen-analysis.mjs from server/text/stopwords/*.json; do not edit\n';
  out += "// The per-language stop-word lists collocations hide by default (SPEC §4.6), folded (u61m-1), in the reference's order.\n\n";
  out += 'enum Stopwords {\n  static let lists: [String: [String]] = [\n';
  for (const l of langs) {
    const words = JSON.parse(readFileSync(join(dir, `${l}.json`), 'utf8')).words;
    out += `    ${JSON.stringify(l)}: [${words.map((w) => JSON.stringify(w)).join(', ')}],\n`;
  }
  out += '  ]\n}\n';
  ctx.writeGenerated('ScrollsKit/Sources/ScrollsAnalysis/Collocations/Stopwords.swift', out);
}

