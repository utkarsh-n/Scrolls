/** The reference's route of a module, on a clone: the main connection writes compare_log, a read-only one computes. */
async function routeRunner(clone) {
  process.env.SCROLLS_DATA = clone.dir;
  const { openDb } = await imp('../../server/db/open.mjs');
  const { toErrorBody, statusOf } = await imp('../../server/http/errors.mjs');
  const main = openDb({ path: clone.db });
  const read = openDb({ path: clone.db, readOnly: true });
  const pool = { run: async (url, fn, args) => (await import(url))[fn](read, args) };
  const call = async (route, req) => {
    try {
      const out = await route.handler(req, { db: main, pool });
      return { status: 200, body: out.json };
    } catch (err) {
      return { status: statusOf(err), body: toErrorBody(err) };
    }
  };
  return { main, read, call, close: () => { read.close(); main.close(); } };
}

/** Redacts the passage text of restricted collections in KWIC rows (§2.6). */
function redactRows(body, redactor) {
  const fix = (rows) => {
    if (!Array.isArray(rows)) return rows;
    return rows.map((r) => (r && typeof r === 'object' && typeof r.collection === 'string' && !redactor.isOpen(r.collection)
      ? { ...r, left: redactor.text(r.collection, r.left), match: redactor.text(r.collection, r.match), right: redactor.text(r.collection, r.right) }
      : r));
  };
  if (body?.passages) body.passages = { ...body.passages, a: fix(body.passages.a), b: fix(body.passages.b) };
  if (body?.kwic) body.kwic = fix(body.kwic);
  return body;
}

async function cloneWithDerived(ctx, name) {
  const c = ctx.cloneSnapshot(name);
  const tokens = join(ctx.snapshots, name, 'derived', 'tokens');
  if (existsSync(tokens)) {
    mkdirSync(join(c.dir, 'derived'), { recursive: true });
    execFileSync('/bin/cp', ['-c', '-R', tokens, join(c.dir, 'derived', 'tokens')]);
  }
  return c;
}

async function g3(ctx, kind) {
  const cases = [];
  const inputs = {};
  for (const snapshot of ['m1r', 'm5r']) {
    if (!ctx.findSnapshot([snapshot])) throw new Error(`${kind}: snapshot ${snapshot} is missing`);
    inputs[snapshot] = ctx.snapshotInfo(snapshot)?.files?.['scrolls.db']?.sha256 ?? null;
    const clone = await cloneWithDerived(ctx, snapshot);
    try {
      const runner = await routeRunner(clone);
      const redactor = makeRedactor(runner.read);
      try {
        if (kind === 'compare') {
          const { routes } = await imp('../../server/routes/compare.mjs');
          let i = 0;
          for (const [session, body] of compareRequests(snapshot)) {
            const t0 = Date.now();
            const res = await runner.call(routes[0], { body, sessionId: session });
            ctx.log(`compare ${snapshot} #${i}: ${res.status} in ${Date.now() - t0} ms`);
            cases.push({ id: `${snapshot}-${String(i++).padStart(2, '0')}`, snapshot, session, request: body, status: res.status,
              body: normalize(redactRows(res.body, redactor)) });
          }
        } else {
          const { routes } = await imp('../../server/routes/collocations.mjs');
          let i = 0;
          for (const query of collocationRequests(snapshot)) {
            const t0 = Date.now();
            const { toggles, ...rest } = query;
            const q = { ...rest, ...(toggles ?? {}) };
            const res = await runner.call(routes[0], { query: q });
            ctx.log(`collocations ${snapshot} #${i}: ${res.status} in ${Date.now() - t0} ms`);
            cases.push({ id: `${snapshot}-${String(i++).padStart(2, '0')}`, snapshot, request: query, status: res.status,
              body: normalize(redactRows(res.body, redactor)) });
          }
        }
      } finally {
        runner.close();
      }
    } finally {
      clone.cleanup();
    }
  }
  ctx.inputs = { snapshots: inputs, environment: 'no bin/scrolls-nl, no sources/ (Ngram not staged); derived/tokens copied' };
  return cases;
}

